SELECT
    p.ID AS PORTFOLIO_ID,
    p.NAME AS PORTFOLIO_NAME,
    p.BASE_CURRENCY,
    COUNT(pos.ID) AS POSITION_COUNT,
    NVL(SUM(pos.QUANTITY_MWH), 0) AS NET_EXPOSURE_MWH
FROM PORTFOLIOS p
LEFT JOIN POSITIONS pos
    ON pos.PORTFOLIO_ID = p.ID
GROUP BY
    p.ID,
    p.NAME,
    p.BASE_CURRENCY
ORDER BY
    NET_EXPOSURE_MWH DESC;