SELECT
    t.ID AS TRADE_ID,
    t.ENERGY_OFFER_ID,
    t.SELLER_ID,
    t.BUYER_ID,
    t.ENERGY_TYPE,
    t.QUANTITY_MWH,
    t.PRICE_PER_MWH,
    t.CURRENCY,
    t.CREATED_AT,
    eo.PORTFOLIO_ID AS SELLER_PORTFOLIO_ID,
    eo.STATUS AS OFFER_STATUS
FROM TRADES t
INNER JOIN ENERGY_OFFERS eo
    ON eo.ID = t.ENERGY_OFFER_ID
ORDER BY t.CREATED_AT DESC;