CREATE OR REPLACE TRIGGER TRG_ENERGY_OFFER_STATUS_AUDIT
AFTER UPDATE OF STATUS
ON ENERGY_OFFERS
FOR EACH ROW
WHEN (OLD.STATUS <> NEW.STATUS)
BEGIN
    INSERT INTO ENERGY_OFFER_AUDIT
    (
        ENERGY_OFFER_ID,
        OLD_STATUS,
        NEW_STATUS,
        CHANGED_AT
    )
    VALUES
    (
        :OLD.ID,
        :OLD.STATUS,
        :NEW.STATUS,
        SYSTIMESTAMP
    );
END;
